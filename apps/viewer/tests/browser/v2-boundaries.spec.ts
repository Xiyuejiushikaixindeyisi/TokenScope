import { test, expect } from '@playwright/test';
import examples from '../../../../docs/contracts/user-monitoring-v2/2.0.0/runtime.examples.json' with { type: 'json' };
test.beforeEach(() => test.skip(process.env.TOKENSCOPE_REAL_BACKEND !== '1', 'isolated backend'));
test('real legacy TTFT read, new limits, missing W and forbidden O', async ({ page }) => {
    await page.goto('/#/users');
    const setup = await page.evaluate(async (legacy) => {
        const c = await fetch('/monitoring/catalog').then(r => r.json()), headers = { 'Content-Type': 'application/json', 'X-TokenScope-Instance-Id': c.service_instance_id };
        const post = async (path: string, body: unknown) => { const r = await fetch('/monitoring/user-v2' + path, { method: 'POST', headers, body: JSON.stringify(body) }); return { status: r.status, body: await r.json() }; };
        const run = (await post('/runs', { submission_key: 'mv2-f006-user-1', file_ref: 'model-1.csv', model_id: 'GLM-5.2', common_name: 'GLM-V5.2' })).body;
        const rank = await fetch(`/monitoring/user-v2/runs/${run.user_run_id}/rankings`, { headers }).then(r => r.json());
        const appid = rank.rows[0].appid;
        const scenario = { ...legacy, scenario_id: 'browser-legacy' };
        const registered = await post('/scenarios', scenario);
        const request = { submission_key: 'browser-legacy-eval', user_run_id: run.user_run_id, appid, scenario_id: 'browser-legacy', scenario_revision: '1', target_seconds: '8', waiting_seconds: '2', comparator: 'le' };
        const history = await post('/evaluations', request);
        const modern = { timing_model: 'batch_reference_total_noncompute_v1', scenario_id: 'browser-boundary', revision: '1', model_id: 'GLM-5.2', common_name: 'GLM-V5.2', deployment: 'synthetic', source: 'user_assumption', source_description: 'synthetic only', chunk_tokens: '8192', chunk_seconds: '1' };
        const invalid = await post('/scenarios', { ...modern, overhead_seconds: '0' });
        await post('/scenarios', modern);
        const base = { ...request, scenario_id: 'browser-boundary' };
        const zero = await post('/evaluations', { ...base, submission_key: 'browser-zero', target_seconds: '100', waiting_seconds: '0' });
        const full = await post('/evaluations', { ...base, submission_key: 'browser-full', target_seconds: '0.5', waiting_seconds: '0' });
        const none = await post('/evaluations', { ...base, submission_key: 'browser-none', target_seconds: '1', waiting_seconds: '2' });
        const { waiting_seconds: unused, ...missing } = base;
        void unused;
        const absent = await post('/evaluations', { ...missing, submission_key: 'browser-absent' });
        return { run, registered, history, invalid, zero, full, none, absent };
    }, examples.find(x => x.timing === 'legacy' && x.model === 'GLM-5.2')!.response.scenario);
    expect(setup.registered.status).toBeLessThan(300);
    expect(setup.invalid.status).toBe(422);
    expect(setup.absent.status).toBe(422);
    expect(setup.zero.body.required_hit_rate).toBe(0);
    expect(setup.full.body.required_hit_rate).toBe(1);
    expect(setup.none.body.status).toBe('no_budget');
    await page.getByRole('button', { name: '打开运行', exact: true }).click();
    await page.locator('input[name=run]').fill(setup.run.user_run_id);
    await page.getByRole('button', { name: '打开', exact: true }).click();
    await expect(page.locator('.ttft-panel')).toBeVisible();
    await page.getByRole('button', { name: '设置评估条件' }).click();
    await page.locator('input[name=evaluation_id]').fill(setup.history.body.evaluation_id);
    await page.getByRole('button', { name: '读取历史评估' }).click();
    await expect(page.getByRole('heading', { name: '历史W+O口径 · 只读快照' })).toBeVisible();
    await expect(page.locator('article.notice')).toContainText('O=1s');
    await expect(page.getByLabel('非计算耗时W')).toHaveValue('');
});
test('synthetic contract projection: 20 paging, big integer, null and >200K tied modes', async ({ page }) => {
    await page.goto('/#/users');
    const setup = await page.evaluate(async () => { const c = await fetch('/monitoring/catalog').then(r => r.json()), headers = { 'Content-Type': 'application/json', 'X-TokenScope-Instance-Id': c.service_instance_id }; const run = await fetch('/monitoring/user-v2/runs', { method: 'POST', headers, body: JSON.stringify({ submission_key: 'mv2-f006-user-1', file_ref: 'model-1.csv', model_id: 'GLM-5.2', common_name: 'GLM-V5.2' }) }).then(r => r.json()); const rank = await fetch(`/monitoring/user-v2/runs/${run.user_run_id}/rankings`, { headers }).then(r => r.json()); return { run, rank }; });
    await page.getByRole('button', { name: '打开运行', exact: true }).click();
    await page.locator('input[name=run]').fill(setup.run.user_run_id);
    await page.getByRole('button', { name: '打开', exact: true }).click();
    await expect(page.locator('.metric-grid')).toBeVisible();
    let conflict = true;
    const base = setup.rank.rows[0];
    await page.route('**/rankings?*', route => { const q = new URL(route.request().url()).searchParams, offset = Number(q.get('offset')); if (conflict) {
        conflict = false;
        return route.fulfill({ status: 409, json: { error: { code: 'INDEX_REVISION_CONFLICT', message: 'changed' } } });
    } return route.fulfill({ json: { ...setup.rank, total: '25', next_offset: offset === 0 ? '20' : null, rows: Array.from({ length: offset === 0 ? 20 : 5 }, (_, j) => ({ ...base, appid: `APP-${offset + j}`, total_ideal_compute_tokens: '9007199254740993123', ideal_hit_rate: j === 0 ? null : base.ideal_hit_rate, tie_count: '25' })) } }); });
    await page.route('**/modes?*', route => { const offset = Number(new URL(route.request().url()).searchParams.get('offset')); return route.fulfill({ json: { user_run_id: setup.run.user_run_id, appid: 'APP-20', index_revision: setup.rank.index_revision, bin_width: 5000, total: '25', next_offset: offset === 0 ? '20' : null, bins: Array.from({ length: offset === 0 ? 20 : 5 }, (_, j) => ({ ...base.representative_bin, lower: String(200000 + (offset + j) * 5000), upper: String(205000 + (offset + j) * 5000) })) } }); });
    await page.locator('.sidebar a[href="#/users/ranking"]').click();
    await expect(page.locator('.v2-rank-table tbody tr')).toHaveCount(20);
    await expect(page.locator('.v2-rank-table tbody tr').first()).toContainText('9,007,199,254,740,993,123');
    await expect(page.locator('.v2-rank-table tbody tr').first()).toContainText('—');
    await page.locator('.v2-pagination').getByRole('button', { name: '下一页' }).click();
    await expect(page.locator('.v2-rank-table tbody tr')).toHaveCount(5);
    await page.locator('.v2-rank-table tbody tr').first().getByRole('button', { name: '查看 25 个众数区间' }).click();
    await expect(page.locator('dialog tbody tr')).toHaveCount(20);
    await expect(page.locator('dialog')).toContainText('200000');
    await page.locator('dialog').getByRole('button', { name: '下一页' }).click();
    await expect(page.locator('dialog tbody tr')).toHaveCount(5);
    await expect(page.locator('dialog')).toContainText('300000');
});
